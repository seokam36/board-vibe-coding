-- 하는 일: 비자 후기 표 추가 (S11-a). 이 단계는 표·인덱스만 만들고 동작은 바뀌지 않는다. 기존 데이터에는 영향이 없다.
-- 이미 올라간 V1~V6은 고치지 않고, 바뀌는 건 전부 이 새 파일에 쓴다.
-- 제약에 이름을 붙이는 이유: 서비스가 깨진 제약 이름으로 오류 종류를 구분한다.

-- 비자 후기 표: 한 건 = 학교 인증 회원이 쓴 비자 신청 결과 하나.
CREATE TABLE visa_reviews (
    id               bigint      NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    author_id        bigint,                 -- 탈퇴 시 NULL (글·댓글과 같은 방식)
    school_id        bigint      NOT NULL,   -- 작성 시점 인증 학교 복사. 탈퇴해도 남아 통계 유지
    visa_type        varchar(20) NOT NULL,
    application_type varchar(20) NOT NULL,
    received_date    date        NOT NULL,
    result_date      date        NOT NULL,
    result           varchar(20) NOT NULL,
    content          text        NOT NULL DEFAULT '',
    created_at       timestamp(6) with time zone NOT NULL,
    CONSTRAINT visa_reviews_pkey PRIMARY KEY (id),
    -- author_id는 글·댓글처럼 ON DELETE 동작이 없다. 탈퇴 때 서비스가 먼저 NULL로 바꾼다(S11-c).
    CONSTRAINT fk_visa_reviews_author FOREIGN KEY (author_id) REFERENCES users (id),
    CONSTRAINT fk_visa_reviews_school FOREIGN KEY (school_id) REFERENCES schools (id),
    -- enum 값 목록을 DB도 한 번 더 지킨다 (값을 늘리려면 enum과 이 제약을 새 V 파일로 같이 바꾼다)
    CONSTRAINT ck_visa_reviews_visa_type        CHECK (visa_type IN ('D_2','D_4','D_10','E_7','OTHER')),
    CONSTRAINT ck_visa_reviews_application_type CHECK (application_type IN ('NEW','REGISTRATION','EXTENSION','CHANGE','OTHER')),
    CONSTRAINT ck_visa_reviews_result           CHECK (result IN ('APPROVED','DENIED')),
    -- 결과 받은 날이 접수일보다 앞설 수 없다
    CONSTRAINT ck_visa_reviews_dates            CHECK (result_date >= received_date)
);

-- 학교별 통계(학교·비자 종류·신청 종류로 묶어 세기)가 표 전체를 훑지 않게 한다
CREATE INDEX idx_visa_reviews_stats ON visa_reviews (school_id, visa_type, application_type);
-- 탈퇴 때 "이 회원이 쓴 후기" 찾기가 표 전체를 훑지 않게 한다
CREATE INDEX idx_visa_reviews_author_id ON visa_reviews (author_id);
-- (S10 리뷰에서 미룬 것) 학교별 인증 회원 수 세기·삭제 확인이 users 전체를 훑지 않게 한다
CREATE INDEX idx_users_verified_school_id ON users (verified_school_id);
