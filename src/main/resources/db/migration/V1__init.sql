-- 회원 표. FK 때문에 posts보다 먼저 만든다.
CREATE TABLE users (
    id         bigint                   NOT NULL GENERATED BY DEFAULT AS IDENTITY, -- 자동 번호(시퀀스 users_id_seq)
    created_at timestamp(6) with time zone NOT NULL,
    password   character varying(100)   NOT NULL, -- 해시된 비밀번호
    username   character varying(20)    NOT NULL,
    nickname   character varying(20)    NOT NULL,
    CONSTRAINT users_pkey PRIMARY KEY (id),
    -- 닉네임 중복 방지
    CONSTRAINT uk2ty1xmrrgtn89xt7kyxx6ta7h UNIQUE (nickname),
    -- 아이디 중복 방지
    CONSTRAINT ukr43af9ap4edm43mmtq01oddj6 UNIQUE (username)
);

-- 게시글 표. author_id는 작성자(users.id)를 가리킨다.
CREATE TABLE posts (
    id         bigint                   NOT NULL GENERATED BY DEFAULT AS IDENTITY, -- 자동 번호(시퀀스 posts_id_seq)
    content    text                     NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    title      character varying(100)   NOT NULL,
    author_id  bigint,
    CONSTRAINT posts_pkey PRIMARY KEY (id),
    CONSTRAINT fk6xvn0811tkyo3nfjk2xvqx6ns FOREIGN KEY (author_id) REFERENCES users (id)
);
