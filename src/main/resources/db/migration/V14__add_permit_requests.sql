-- 하는 일: 표준입학허가서 인증 "신청" 표(permit_requests)와 학교 이름 별칭 표(school_name_aliases) 추가 (S20-a).
-- 표만 새로 만들고 기존 표·칸(users.verified_school_id 등)은 건드리지 않는다. 이미 올라간 V1~V13은 고치지 않는다.
-- 제약에 이름을 붙이는 이유: 서비스가 깨진 제약 이름으로 오류 종류(409 등)를 구분한다.

-- 허가서 인증 신청 한 건. 승인되면 users.verified_school_id에 학교가 들어간다(승인 처리는 S20-b·S20-d).
CREATE TABLE permit_requests (
    id                 bigint       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    user_id            bigint       NOT NULL,  -- 신청한 회원. 회원이 탈퇴하면 신청 행도 DB가 같이 지운다(사진 파일 정리는 서비스 몫)
    status             varchar(20)  NOT NULL,  -- PENDING(대기) / APPROVED(승인) / REJECTED(거절)
    photo_key          varchar(255),           -- 창고(PhotoStorage)에 둔 허가서 사진 이름. 결과가 나와 사진을 지우면 NULL
    content_type       varchar(20),            -- 사진 종류(image/jpeg, image/png). 사진을 지우면 NULL
    school_id          bigint,                 -- 승인된 학교
    detected_school_id bigint,                 -- 기계가 글자에서 추정한 학교(S20-d에서 채움)
    -- 기계 판독 결과 종류. 값 목록은 S20-d에서 정하므로 이번엔 CHECK 없이 넉넉한 길이로만 둔다(나중에 CHECK는 새 V 파일로 건다)
    machine_result     varchar(30),
    auto_decided       boolean      NOT NULL DEFAULT false,  -- 기계가 자동으로 결정했는가
    permit_number_hash varchar(64),            -- 허가서 번호의 해시(같은 허가서로 여러 계정이 인증하는 것 방지, S20-d)
    reject_reason      varchar(30),            -- 거절 이유 코드(고정 목록)
    created_at         timestamp(6) with time zone NOT NULL,
    decided_at         timestamp(6) with time zone,
    decided_by         bigint,                 -- 결정한 관리자(기계 결정이면 NULL)
    CONSTRAINT permit_requests_pkey PRIMARY KEY (id),
    CONSTRAINT fk_permit_requests_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_permit_requests_school FOREIGN KEY (school_id) REFERENCES schools (id),
    CONSTRAINT fk_permit_requests_detected_school FOREIGN KEY (detected_school_id) REFERENCES schools (id),
    CONSTRAINT fk_permit_requests_decider FOREIGN KEY (decided_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT ck_permit_requests_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    CONSTRAINT ck_permit_requests_reason CHECK (reject_reason IS NULL OR reject_reason IN
        ('BLURRY', 'NOT_PERMIT', 'NOT_MASKED', 'UNSUPPORTED_SCHOOL', 'DUPLICATE', 'EXPIRED', 'OTHER'))
);

-- 회원당 "대기(PENDING)" 신청은 1건만: PENDING인 줄만 대상인 부분 UNIQUE 인덱스.
-- 동시에 신청이 2개 와도 DB가 하나만 통과시킨다(서비스는 이 이름으로 409를 구분한다). 승인·거절된 옛 줄은 여러 개여도 된다.
CREATE UNIQUE INDEX uk_permit_requests_user_pending ON permit_requests (user_id) WHERE status = 'PENDING';

-- 같은 허가서(번호 해시)로 승인된 신청은 1건만: APPROVED인 줄만 대상인 부분 UNIQUE 인덱스.
-- 전체 UNIQUE면 반려된 신청에 해시가 남았을 때 같은 허가서를 다시 신청하면 제약 위반(500)이 되므로 승인된 줄에만 건다(S20-d가 쓴다).
CREATE UNIQUE INDEX uk_permit_requests_permit_hash ON permit_requests (permit_number_hash) WHERE status = 'APPROVED';

-- "이 회원의 신청들" 조회·삭제가 표 전체를 훑지 않게 한다
CREATE INDEX idx_permit_requests_user_id ON permit_requests (user_id, id DESC);

-- 허가서에 적힌 학교 이름(영문·약칭 포함)을 우리 학교로 바꾸는 별칭 표. 이번엔 표와 값만 만들고, 쓰는 코드는 S20-d.
CREATE TABLE school_name_aliases (
    id        bigint       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    school_id bigint       NOT NULL,
    alias     varchar(100) NOT NULL,
    CONSTRAINT school_name_aliases_pkey PRIMARY KEY (id),
    CONSTRAINT fk_school_name_aliases_school FOREIGN KEY (school_id) REFERENCES schools (id),
    CONSTRAINT uk_school_name_aliases_alias UNIQUE (alias),
    -- 별칭은 소문자로만 저장한다(비교할 때 글자를 소문자로 바꿔 정확히 일치만 인정)
    CONSTRAINT ck_school_name_aliases_lower CHECK (alias = lower(alias))
);

