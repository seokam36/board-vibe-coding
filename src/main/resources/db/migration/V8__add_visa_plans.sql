-- 하는 일: 내 비자 일정 표 추가 (S12-a). 회원마다 "체류 만료일" 하나만 적어 두는 표다.
-- 표만 새로 만들고 기존 표·데이터는 건드리지 않는다(채울 데이터 없음). 이미 올라간 V1~V7은 고치지 않는다.
-- 제약에 이름을 붙이는 이유: 서비스가 깨진 제약 이름으로 오류 종류를 구분한다.

CREATE TABLE visa_plans (
    id          bigint       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    user_id     bigint       NOT NULL,
    expiry_date date         NOT NULL,   -- 체류 만료일 (서울 오늘~오늘+5년은 서비스가 검사)
    created_at  timestamp(6) with time zone NOT NULL,
    updated_at  timestamp(6) with time zone NOT NULL,
    CONSTRAINT visa_plans_pkey PRIMARY KEY (id),
    -- 회원당 일정 1개: 같은 회원이 두 번 등록하면 이 제약이 막는다(PUT은 이 제약을 이용해 "있으면 덮어쓰기"를 한다)
    CONSTRAINT uk_visa_plans_user UNIQUE (user_id),
    -- 회원이 탈퇴하면 일정도 DB가 같이 지운다(UserService.withdraw를 고칠 필요 없음)
    CONSTRAINT fk_visa_plans_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);
