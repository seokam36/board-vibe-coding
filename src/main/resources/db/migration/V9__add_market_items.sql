-- 하는 일: 중고거래·나눔 게시판의 물건 글 표 추가 (S13-a). 표·인덱스만 새로 만들고 기존 표·데이터는 건드리지 않는다.
-- 이미 올라간 V1~V8은 고치지 않는다. 제약에 이름을 붙이는 이유: 서비스가 깨진 제약 이름으로 오류 종류를 구분한다.

CREATE TABLE market_items (
    id         bigint       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    seller_id  bigint       NOT NULL,   -- 판매자(글쓴이)
    school_id  bigint       NOT NULL,   -- 올린 시점 판매자의 인증 학교를 복사해 둔다
    title      varchar(100) NOT NULL,
    content    text         NOT NULL,
    trade_type varchar(20)  NOT NULL,   -- SALE(판매) / FREE(나눔)
    price      integer      NOT NULL,   -- 나눔은 0
    status     varchar(20)  NOT NULL,   -- ON_SALE(판매중) / RESERVED(예약중) / DONE(거래완료)
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT market_items_pkey PRIMARY KEY (id),
    -- 판매자가 탈퇴하면 DB가 물건 글도 같이 지운다(UserService.withdraw를 고칠 필요 없음. 비자 일정 V8과 같은 방식)
    CONSTRAINT fk_market_items_seller FOREIGN KEY (seller_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_market_items_school FOREIGN KEY (school_id) REFERENCES schools (id),
    -- enum 값 목록을 DB도 한 번 더 지킨다 (값을 늘리려면 enum과 이 제약을 새 V 파일로 같이 바꾼다)
    CONSTRAINT ck_market_items_trade_type CHECK (trade_type IN ('SALE','FREE')),
    CONSTRAINT ck_market_items_status     CHECK (status IN ('ON_SALE','RESERVED','DONE')),
    -- 나눔은 가격 0, 판매는 1~10,000,000원
    CONSTRAINT ck_market_items_price      CHECK ((trade_type = 'FREE' AND price = 0)
                                              OR (trade_type = 'SALE' AND price BETWEEN 1 AND 10000000))
);

-- 학교별·상태별 목록(다음 단계)이 표 전체를 훑지 않게 한다
CREATE INDEX idx_market_items_school_status ON market_items (school_id, status);
-- "이 판매자의 글" 찾기가 표 전체를 훑지 않게 한다
CREATE INDEX idx_market_items_seller_id ON market_items (seller_id);
