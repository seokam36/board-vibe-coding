-- 하는 일: 신고(reports) 표를 새로 만든다 (S9-b). 기존 표는 건드리지 않는다.

-- 신고 한 건. 대상은 글 또는 댓글 중 정확히 하나(ck_reports_target: 둘 중 하나만 NULL).
-- 대상(글/댓글)이 지워지면 신고도 DB가 같이 지운다(CASCADE). 글 삭제 -> 댓글 CASCADE -> 댓글 신고 CASCADE.
-- 신고자가 탈퇴하면 신고는 남기고 reporter_id만 NULL로 비운다(SET NULL).
-- 같은 회원이 같은 대상을 두 번 신고하는 건 UNIQUE가 막는다 (NULL끼리는 서로 다르게 취급돼 탈퇴한 신고자의 신고는 막지 않는다).
CREATE TABLE reports (
    id          bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    post_id     bigint,
    comment_id  bigint,
    reporter_id bigint,
    reason      varchar(20) NOT NULL,
    detail      varchar(300),
    status      varchar(20) NOT NULL DEFAULT 'PENDING',
    created_at  timestamp(6) with time zone NOT NULL,
    CONSTRAINT reports_pkey PRIMARY KEY (id),
    CONSTRAINT fk_reports_post     FOREIGN KEY (post_id)     REFERENCES posts (id)    ON DELETE CASCADE,
    CONSTRAINT fk_reports_comment  FOREIGN KEY (comment_id)  REFERENCES comments (id) ON DELETE CASCADE,
    CONSTRAINT fk_reports_reporter FOREIGN KEY (reporter_id) REFERENCES users (id)    ON DELETE SET NULL,
    CONSTRAINT uk_reports_post_reporter    UNIQUE (post_id, reporter_id),
    CONSTRAINT uk_reports_comment_reporter UNIQUE (comment_id, reporter_id),
    CONSTRAINT ck_reports_target CHECK ((post_id IS NULL) <> (comment_id IS NULL)),
    CONSTRAINT ck_reports_reason CHECK (reason IN ('SPAM', 'ABUSE', 'SEXUAL', 'PRIVACY', 'OTHER')),
    CONSTRAINT ck_reports_status CHECK (status IN ('PENDING', 'DISMISSED'))
);
-- 처리 대기 목록을 id순으로 읽는 관리자 화면(S9-c)을 빠르게 한다
CREATE INDEX idx_reports_status_id ON reports (status, id);
-- 탈퇴 때 FK(SET NULL)가 "이 회원의 신고"를 찾을 때 표 전체를 훑지 않게 한다
CREATE INDEX idx_reports_reporter_id ON reports (reporter_id);
-- 글·댓글 삭제 때 FK(CASCADE)가 "이 대상의 신고"를 찾는 건 UNIQUE의 첫 칸(post_id / comment_id) 인덱스가 맡는다
