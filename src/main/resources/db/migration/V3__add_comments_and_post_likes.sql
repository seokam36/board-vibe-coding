-- 하는 일: 댓글(comments)과 공감(post_likes) 표를 새로 만든다 (S8-a). 기존 표는 건드리지 않는다.

-- 댓글 표. 글이 지워지면 댓글도 DB가 같이 지운다(ON DELETE CASCADE).
-- author_id는 글처럼 탈퇴 시 NULL로 비우므로 NULL 허용, CASCADE 없음.
CREATE TABLE comments (
    id         bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    post_id    bigint NOT NULL,
    author_id  bigint,
    content    varchar(1000) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT comments_pkey PRIMARY KEY (id),
    CONSTRAINT fk_comments_post   FOREIGN KEY (post_id)   REFERENCES posts (id) ON DELETE CASCADE,
    CONSTRAINT fk_comments_author FOREIGN KEY (author_id) REFERENCES users (id)
);
-- 글별 댓글을 id순으로 읽는 목록을 빠르게 한다
CREATE INDEX idx_comments_post_id_id ON comments (post_id, id);
-- 탈퇴 때 "이 회원이 쓴 댓글" 찾기(clearAuthor)가 표 전체를 훑지 않게 한다
CREATE INDEX idx_comments_author_id ON comments (author_id);

-- 공감 표(엔티티·API는 S8-b). 한 회원이 한 글에 한 번만(UNIQUE). 글이 지워지거나 회원이 탈퇴하면 같이 지운다.
CREATE TABLE post_likes (
    id         bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    post_id    bigint NOT NULL,
    user_id    bigint NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT post_likes_pkey PRIMARY KEY (id),
    CONSTRAINT uk_post_likes_post_user UNIQUE (post_id, user_id),
    CONSTRAINT fk_post_likes_post FOREIGN KEY (post_id) REFERENCES posts (id) ON DELETE CASCADE,
    CONSTRAINT fk_post_likes_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);
-- 탈퇴 때 회원 FK CASCADE 삭제가 표 전체를 훑지 않게 한다 (UNIQUE는 post_id가 앞이라 user_id 단독 조회엔 못 쓴다)
CREATE INDEX idx_post_likes_user_id ON post_likes (user_id);
