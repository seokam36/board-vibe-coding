-- 글의 학교: 기존 글은 학교가 없어서 NULL 허용
ALTER TABLE posts ADD COLUMN school_id bigint;
ALTER TABLE posts ADD CONSTRAINT fk_posts_school FOREIGN KEY (school_id) REFERENCES schools (id);

-- 글의 말머리: 먼저 칸을 만들고, 기존 글을 CHAT(잡담)으로 채운 뒤 NOT NULL + 허용 값 검사를 건다
ALTER TABLE posts ADD COLUMN category varchar(20);
UPDATE posts SET category = 'CHAT' WHERE category IS NULL;
ALTER TABLE posts ALTER COLUMN category SET NOT NULL;
ALTER TABLE posts ADD CONSTRAINT ck_posts_category CHECK (category IN ('CHAT', 'QUESTION', 'CAMPUS_LIFE'));
-- 기본값 CHAT: 배포 후 옛 이미지(category를 모르는 코드)로 되돌려도 글쓰기가 실패하지 않게 한다. 새 코드는 항상 값을 직접 넣는다.
ALTER TABLE posts ALTER COLUMN category SET DEFAULT 'CHAT';

-- 학교별 최신순 목록(S7-b)을 빠르게 하기 위한 인덱스
CREATE INDEX idx_posts_school_id_id_desc ON posts (school_id, id DESC);
