-- 하는 일: 비자 일정 푸시 알림 "보낸 기록" 표 추가 (S24-c). (회원, 만료일, 단계)마다 한 번만 보내려고 적어 둔다.
-- 표만 새로 만들고 기존 표·데이터는 건드리지 않는다(채울 데이터 없음). 이미 올라간 V1~V16은 고치지 않는다.
-- 제약에 이름을 붙이는 이유: 오류가 났을 때 어떤 제약이 깨졌는지 이름으로 구분한다.

CREATE TABLE visa_plan_notifications (
    id          bigint       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    user_id     bigint       NOT NULL,
    expiry_date date         NOT NULL,   -- 알림을 보낼 때의 체류 만료일 (만료일을 바꾸면 새 기록이라 다시 보낼 수 있다)
    stage       varchar(20)  NOT NULL,   -- 보낸 단계 (VisaPlanStage 이름, EXPIRED는 보내지 않으므로 없음)
    sent_at     timestamp(6) with time zone NOT NULL,
    CONSTRAINT visa_plan_notifications_pkey PRIMARY KEY (id),
    CONSTRAINT ck_visa_plan_notifications_stage CHECK (stage IN ('PREPARE', 'CHECK', 'URGENT')),
    -- 같은 (회원, 만료일, 단계)는 한 번만: 주기 작업이 겹쳐 돌아도 두 번 기록되지 않는다
    CONSTRAINT uk_visa_plan_notifications_user_expiry_stage UNIQUE (user_id, expiry_date, stage),
    -- 회원이 탈퇴하면 기록도 DB가 같이 지운다
    CONSTRAINT fk_visa_plan_notifications_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);
