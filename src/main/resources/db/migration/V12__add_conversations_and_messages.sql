-- 하는 일: 쪽지(대화방 방식)용 표 두 개를 새로 만든다 (S14-a). 기존 표·데이터는 건드리지 않는다.
-- 이미 올라간 V1~V11은 고치지 않는다. 제약·인덱스에 이름을 붙이는 이유: 서비스가 깨진 제약 이름으로 오류 종류(404/401)를 구분한다.

-- 대화방: "중고 글 + 구매자" 한 쌍에 방 1개. 같은 글에 다시 쪽지를 보내면 기존 방에 붙는다.
CREATE TABLE conversations (
    id              bigint       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    market_item_id  bigint,                        -- 글이 지워지면 NULL (대화는 남는다)
    item_title      varchar(100) NOT NULL,         -- 방을 만들 때 글 제목을 복사해 둔다(글이 지워져도 제목을 보여 주려고). market_items.title과 같은 길이
    buyer_id        bigint,                        -- 구매자(쪽지를 먼저 보낸 사람). 탈퇴하면 NULL
    seller_id       bigint,                        -- 판매자. 탈퇴하면 NULL
    created_at      timestamp(6) with time zone NOT NULL,
    last_message_at timestamp(6) with time zone NOT NULL,  -- 마지막 쪽지 시각(목록 정렬용)
    CONSTRAINT conversations_pkey PRIMARY KEY (id),
    -- 글·회원이 지워져도 대화는 남기려고 ON DELETE SET NULL (UserService.withdraw를 고칠 필요 없음)
    CONSTRAINT fk_conversations_item   FOREIGN KEY (market_item_id) REFERENCES market_items (id) ON DELETE SET NULL,
    CONSTRAINT fk_conversations_buyer  FOREIGN KEY (buyer_id)       REFERENCES users (id)        ON DELETE SET NULL,
    CONSTRAINT fk_conversations_seller FOREIGN KEY (seller_id)      REFERENCES users (id)        ON DELETE SET NULL,
    -- 글 하나에 구매자 한 명당 방은 하나. 동시에 두 번 보내도 방이 둘 생기지 않게 DB가 막는다.
    -- (이 UNIQUE의 첫 칸 market_item_id 인덱스가 글 삭제 때 SET NULL이 "이 글의 방"을 찾는 일도 맡는다)
    CONSTRAINT uk_conversations_item_buyer UNIQUE (market_item_id, buyer_id),
    -- 자기 자신과의 대화방은 없다 (둘 중 하나가 NULL이면 비교 결과가 NULL이라 통과 = 탈퇴한 방은 허용)
    CONSTRAINT ck_conversations_buyer_not_seller CHECK (buyer_id <> seller_id)
);

-- "내 대화방" 목록(다음 단계)이 표 전체를 훑지 않게 한다
CREATE INDEX idx_conversations_buyer_id  ON conversations (buyer_id);
CREATE INDEX idx_conversations_seller_id ON conversations (seller_id);

-- 쪽지: 대화방 안의 메시지 한 통. 수정·삭제 없음.
CREATE TABLE messages (
    id              bigint        NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    conversation_id bigint        NOT NULL,
    sender_id       bigint,                         -- 보낸 사람. 탈퇴하면 NULL
    content         varchar(1000) NOT NULL,
    created_at      timestamp(6) with time zone NOT NULL,
    read_at         timestamp(6) with time zone,    -- 읽은 시각(S14-c용, 지금은 안 쓴다)
    CONSTRAINT messages_pkey PRIMARY KEY (id),
    -- 방이 지워지면 쪽지도 같이 지운다
    CONSTRAINT fk_messages_conversation FOREIGN KEY (conversation_id) REFERENCES conversations (id) ON DELETE CASCADE,
    CONSTRAINT fk_messages_sender       FOREIGN KEY (sender_id)       REFERENCES users (id)         ON DELETE SET NULL,
    -- 공백뿐인 쪽지는 서비스가 400으로 막지만 DB도 한 번 더 지킨다
    CONSTRAINT ck_messages_content_not_blank CHECK (char_length(btrim(content)) > 0)
);

-- "이 방의 쪽지를 순서대로" 읽는 일(다음 단계)과 방 삭제 CASCADE가 쓴다
CREATE INDEX idx_messages_conversation_id_id ON messages (conversation_id, id);

-- 회원 탈퇴 때 fk_messages_sender(ON DELETE SET NULL)가 "이 회원이 보낸 쪽지"를 찾는 데 쓴다. 없으면 탈퇴마다 messages 표 전체를 훑는다.
CREATE INDEX idx_messages_sender_id ON messages (sender_id);
