-- 하는 일: 중고 글 사진 표(market_item_photos)와 "창고에서 지울 파일" 대기 표(photo_delete_queue) 추가 (S13-g2).
-- 표만 새로 만들고 기존 표·데이터는 건드리지 않는다. 이미 올라간 V1~V10은 고치지 않는다.
-- 제약에 이름을 붙이는 이유: 오류 메시지와 테스트에서 어떤 규칙에 걸렸는지 바로 알 수 있게 하려고. users를 가리키는 FK는 만들지 않는다(탈퇴는 글 CASCADE로 따라온다).

CREATE TABLE market_item_photos (
    id             bigint       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    market_item_id bigint       NOT NULL,   -- 어느 글의 사진인가
    storage_key    varchar(255) NOT NULL,   -- 창고(PhotoStorage)에 둔 본 사진 이름. 서버 안에서만 쓰고 응답에 내보내지 않는다
    thumb_key      varchar(255) NOT NULL,   -- 창고에 둔 썸네일 이름
    content_type   varchar(20)  NOT NULL,   -- 사진 종류의 유일한 근거(창고에서 꺼낼 때 이 값을 쓴다)
    width          integer      NOT NULL,   -- 본 사진 크기(px)
    height         integer      NOT NULL,
    thumb_width    integer      NOT NULL,   -- 썸네일 크기(px)
    thumb_height   integer      NOT NULL,
    created_at     timestamp(6) with time zone NOT NULL,
    CONSTRAINT market_item_photos_pkey PRIMARY KEY (id),
    -- 글이 지워지면(직접 삭제·판매자 탈퇴) 사진 행도 DB가 같이 지운다. 창고 파일 정리는 서비스 몫(S13-g4)
    CONSTRAINT fk_market_item_photos_item FOREIGN KEY (market_item_id) REFERENCES market_items (id) ON DELETE CASCADE,
    CONSTRAINT uk_market_item_photos_storage_key UNIQUE (storage_key),
    CONSTRAINT uk_market_item_photos_thumb_key   UNIQUE (thumb_key),
    -- 본 사진과 썸네일이 같은 파일을 가리키면 하나를 지울 때 다른 쪽도 사라진다
    CONSTRAINT ck_market_item_photos_keys_differ CHECK (storage_key <> thumb_key),
    CONSTRAINT ck_market_item_photos_content_type CHECK (content_type IN ('image/jpeg', 'image/png')),
    CONSTRAINT ck_market_item_photos_size CHECK (width > 0 AND height > 0 AND thumb_width > 0 AND thumb_height > 0)
);

-- "이 글의 사진들" 조회·개수 세기가 표 전체를 훑지 않게 한다
CREATE INDEX idx_market_item_photos_item_id ON market_item_photos (market_item_id);

-- 창고에서 지워야 하는데 아직 못 지운 파일 목록 (S13-g4에서 사용. 지금은 표만 만든다). FK가 없는 이유: 글·사진 행이 사라진 뒤에도 남아야 하기 때문
CREATE TABLE photo_delete_queue (
    id          bigint       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    storage_key varchar(255) NOT NULL,                       -- 지울 창고 파일 이름
    created_at  timestamp(6) with time zone NOT NULL DEFAULT now(),
    attempts    integer      NOT NULL DEFAULT 0,             -- 지우기를 시도한 횟수
    CONSTRAINT photo_delete_queue_pkey PRIMARY KEY (id),
    CONSTRAINT ck_photo_delete_queue_attempts CHECK (attempts >= 0)
);
