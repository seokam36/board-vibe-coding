-- 하는 일: 학교 메일 인증을 위한 표 변경 (S10-a). 이 단계는 칸·표만 만들고 동작은 바뀌지 않는다.
-- 이미 올라간 V1~V5는 고치지 않고, 바뀌는 건 전부 이 새 파일에 쓴다.

-- 학교별 메일 도메인 표: 학교 하나에 도메인 여러 개 가능, 같은 도메인은 한 학교에만 속한다(정확히 일치만 인정).
-- 제약에 이름을 붙이는 이유: 서비스가 깨진 제약 이름으로 오류 종류를 구분한다.
CREATE TABLE school_email_domains (
    id        bigint       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    school_id bigint       NOT NULL,
    domain    varchar(100) NOT NULL,
    CONSTRAINT school_email_domains_pkey PRIMARY KEY (id),
    CONSTRAINT fk_school_email_domains_school FOREIGN KEY (school_id) REFERENCES schools (id),
    CONSTRAINT uk_school_email_domains_domain UNIQUE (domain),
    -- 메일 도메인은 대소문자 구분이 없으므로 소문자만 허용(대문자 행 때문에 정확히 일치 조회가 갈라지는 것 방지)
    CONSTRAINT ck_school_email_domains_lower CHECK (domain = lower(domain))
);

-- 학교 id를 하드코딩하지 않고 V2에서 넣은 학교 이름으로 찾아서 넣는다
