-- 하는 일: 기기 토큰 표 추가 (S24-a). 푸시 알림(FCM)을 보낼 "휴대폰 주소"를 회원별로 적어 둔다.
-- 표만 새로 만들고 기존 표·데이터는 건드리지 않는다(채울 데이터 없음). 이미 올라간 V1~V15는 고치지 않는다.
-- 제약에 이름을 붙이는 이유: 오류가 났을 때 어떤 제약이 깨졌는지 이름으로 구분한다.

CREATE TABLE device_tokens (
    id          bigint       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    user_id     bigint       NOT NULL,
    token       varchar(4096) NOT NULL,  -- FCM 기기 토큰 (비밀 값 취급: 로그에 남기지 않는다)
    created_at  timestamp(6) with time zone NOT NULL,
    updated_at  timestamp(6) with time zone NOT NULL,
    CONSTRAINT device_tokens_pkey PRIMARY KEY (id),
    -- 같은 토큰은 한 행만: 같은 토큰을 다른 회원이 등록하면 주인을 바꾼다(PUT이 이 제약으로 "있으면 덮어쓰기"를 한다)
    CONSTRAINT uk_device_tokens_token UNIQUE (token),
    -- 회원이 탈퇴하면 토큰도 DB가 같이 지운다(UserService.withdraw를 고칠 필요 없음)
    CONSTRAINT fk_device_tokens_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

-- 회원별 토큰 찾기·개수 세기·오래된 것 지우기용
CREATE INDEX idx_device_tokens_user ON device_tokens (user_id);
